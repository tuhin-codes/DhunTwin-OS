/* ============================================================
   DHUN TWIN OS — ASSET MONITORING TEST LAB
   Repeatable simulation engine for demonstrating scalable
   telemetry and asset monitoring before real hardware is deployed.
   
   Isolates test datasets with `isTestAsset: true` so production
   telemetry and carbon accounting are never contaminated.
   ============================================================ */

import type {
  AssetDomain,
  DataQuality,
  RegisteredAsset,
  RegisteredChannel,
  TelemetryReading,
} from "./types";
import { ASSET_TEMPLATES } from "./assetTemplates";

export interface TestLabScenarioConfig {
  count: number;
  domainDistribution?: Record<AssetDomain, number>;
  includeCoordinatesPercentage?: number; // e.g. 70% have coordinates, 30% do not
  includeAlertsPercentage?: number; // e.g. 10% have out-of-range readings
  datasetTag?: string;
}

export interface PerformanceBenchmarkResult {
  assetCount: number;
  generationMs: number;
  filterMs: number;
  searchMs: number;
  sortMs: number;
  memoryEstimatedKb: number;
}

const TEMPLATE_KEYS = Object.keys(ASSET_TEMPLATES) as (keyof typeof ASSET_TEMPLATES)[];

const PARCELS = [
  { id: "p1", name: "Campus Center · Zone 1", minX: 300, maxX: 480, minY: 200, maxY: 350 },
  { id: "p2", name: "Solar Array West · Zone 2", minX: 80, maxX: 260, minY: 100, maxY: 260 },
  { id: "p3", name: "Water Kiosk & STP · Zone 3", minX: 200, maxX: 360, minY: 320, maxY: 460 },
  { id: "p4", name: "Shared Kitchen & Hub · Zone 4", minX: 420, maxX: 560, minY: 160, maxY: 300 },
  { id: "p5", name: "Residence Blocks · Zone 5", minX: 520, maxX: 720, minY: 120, maxY: 380 },
  { id: "p6", name: "Bioreserve Wilds · Zone 6", minX: 80, maxX: 740, minY: 400, maxY: 480 },
];

/**
 * Generate a deterministic synthetic asset dataset for load & monitoring testing
 */
export function generateTestAssets(config: TestLabScenarioConfig): {
  assets: RegisteredAsset[];
  initialReadings: TelemetryReading[];
  benchmark: PerformanceBenchmarkResult;
} {
  const startTime = performance.now();
  const datasetTag = config.datasetTag || `test-run-${Date.now().toString(36)}`;
  const count = config.count;
  const includeCoordPct = config.includeCoordinatesPercentage ?? 75;
  const includeAlertPct = config.includeAlertsPercentage ?? 10;

  const assets: RegisteredAsset[] = [];
  const initialReadings: TelemetryReading[] = [];

  for (let i = 1; i <= count; i++) {
    const tIndex = (i - 1) % TEMPLATE_KEYS.length;
    const templateKey = TEMPLATE_KEYS[tIndex];
    const template = ASSET_TEMPLATES[templateKey];

    const parcelIndex = (i - 1) % PARCELS.length;
    const parcel = PARCELS[parcelIndex];

    const hasCoords = (i * 17) % 100 < includeCoordPct;
    const isAlerting = (i * 31) % 100 < includeAlertPct;

    const id = `test-${template.domain.toLowerCase()}-${String(i).padStart(count >= 1000 ? 4 : 3, "0")}`;
    const name = `Simulated ${template.type} #${i}`;

    const mapPosition = hasCoords
      ? {
          x: Math.round(parcel.minX + ((i * 37) % (parcel.maxX - parcel.minX))),
          y: Math.round(parcel.minY + ((i * 43) % (parcel.maxY - parcel.minY))),
        }
      : undefined;

    const channels: RegisteredChannel[] = template.channels.map((chTpl) => {
      const channelId = `${id}-${chTpl.id}`;
      return {
        ...chTpl,
        id: channelId,
        channelId,
        assetId: id,
        source: "simulation",
      };
    });

    const primaryChannel = channels[0];

    // Determine value: nominal or alert
    let primaryValue = template.defaultCapacity * (0.6 + ((i * 13) % 35) / 100);
    let quality: DataQuality = "good";

    if (isAlerting && primaryChannel?.alertThresholds?.alarmMax) {
      primaryValue = primaryChannel.alertThresholds.alarmMax * 1.15; // Exceed alarm ceiling
      quality = "degraded";
    }

    const reading: TelemetryReading = {
      assetId: id,
      channelId: primaryChannel ? primaryChannel.id : "ch-1",
      value: Math.round(primaryValue * 100) / 100,
      unit: primaryChannel ? primaryChannel.unit : template.capacityUnit,
      timestamp: new Date(Date.now() - ((i * 7) % 30) * 1000).toISOString(),
      source: "simulation",
      quality,
      notes: "Generated by Dhun Twin OS Repeatable Test Lab",
    };

    initialReadings.push(reading);

    assets.push({
      id,
      assetId: id,
      name,
      type: template.type,
      assetType: template.type,
      subtype: template.subtype,
      assetSubtype: template.subtype,
      domain: template.domain,
      description: `${template.description} [Synthetic Test Lab Instance]`,
      commissioningStatus: i % 15 === 0 ? "Commissioning" : "Active",
      lifecycleStatus: i % 15 === 0 ? "Commissioning" : "Active",
      connectivityStatus: "Connected",
      monitoringMode: "Simulated",
      ratedCapacity: template.defaultCapacity,
      capacityUnit: template.capacityUnit,
      location: {
        parcelId: parcel.id,
        parcelName: parcel.name,
        hasVerifiedCoordinates: hasCoords,
        mapPosition,
        coordinates: hasCoords
          ? {
              lat: 26.9124 + (mapPosition!.y / 500) * 0.015,
              lng: 75.7873 + (mapPosition!.x / 800) * 0.02,
            }
          : undefined,
      },
      channels,
      primaryChannelId: primaryChannel?.id,
      evidenceClassification: "Simulated",
      verificationStatus: "verified",
      isTestAsset: true,
      testDatasetId: datasetTag,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      lastSeenAt: reading.timestamp,
      carbonAccounting: {
        includedInCampusMeter: true, // Prevents double counting in carbon ledger
        eligibleForLedger: false,
      },
    });
  }

  const genEnd = performance.now();
  const generationMs = Math.round((genEnd - startTime) * 100) / 100;

  // Measure filter performance
  const fStart = performance.now();
  assets.filter((a) => a.domain === "Energy");
  const fEnd = performance.now();
  const filterMs = Math.round((fEnd - fStart) * 100) / 100;

  // Measure search performance
  const sStart = performance.now();
  assets.filter((a) => a.name.toLowerCase().includes("05") || a.id.includes("05"));
  const sEnd = performance.now();
  const searchMs = Math.round((sEnd - sStart) * 100) / 100;

  // Measure sort performance
  const sortStart = performance.now();
  [...assets].sort((a, b) => a.name.localeCompare(b.name));
  const sortEnd = performance.now();
  const sortMs = Math.round((sortEnd - sortStart) * 100) / 100;

  const estimatedJsonBytes = JSON.stringify(assets.slice(0, 10)).length * (count / 10);
  const memoryEstimatedKb = Math.round(estimatedJsonBytes / 1024);

  return {
    assets,
    initialReadings,
    benchmark: {
      assetCount: count,
      generationMs,
      filterMs,
      searchMs,
      sortMs,
      memoryEstimatedKb,
    },
  };
}

/**
 * Filter out all test assets, leaving solely authentic physical/production assets
 */
export function purgeTestAssetsFromList(assets: RegisteredAsset[]): RegisteredAsset[] {
  return assets.filter((a) => !a.isTestAsset && !a.id.startsWith("test-"));
}

/**
 * Convenience wrapper for generating test assets by count and optional domain
 */
export function generateTestDataset(
  count: number,
  domain?: AssetDomain
): { assets: RegisteredAsset[]; durationMs: number; readings: TelemetryReading[] } {
  const res = generateTestAssets({
    count,
    domainDistribution: domain ? ({ [domain]: count } as any) : undefined,
  });
  return {
    assets: res.assets,
    durationMs: res.benchmark.generationMs,
    readings: res.initialReadings,
  };
}

/**
 * Benchmark search, filter, and sort performance across an asset dataset
 */
export function benchmarkRegistryPerformance(assets: RegisteredAsset[]): {
  datasetSize: number;
  filterTimeMs: number;
  searchTimeMs: number;
  sortTimeMs: number;
  estimatedMemoryKb: number;
} {
  const fStart = performance.now();
  assets.filter((a) => a.domain === "Energy");
  const fEnd = performance.now();

  const sStart = performance.now();
  assets.filter((a) => a.name.toLowerCase().includes("05") || a.id.includes("05"));
  const sEnd = performance.now();

  const sortStart = performance.now();
  [...assets].sort((a, b) => a.name.localeCompare(b.name));
  const sortEnd = performance.now();

  const estimatedJsonBytes =
    assets.length > 0 ? JSON.stringify(assets.slice(0, 10)).length * (assets.length / 10) : 0;

  return {
    datasetSize: assets.length,
    filterTimeMs: Math.round((fEnd - fStart) * 100) / 100,
    searchTimeMs: Math.round((sEnd - sStart) * 100) / 100,
    sortTimeMs: Math.round((sortEnd - sortStart) * 100) / 100,
    estimatedMemoryKb: Math.round(estimatedJsonBytes / 1024),
  };
}
