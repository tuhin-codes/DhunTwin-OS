export type ProvenanceSourceType =
  | "MEASURED"       // Directly observed site meter telemetry
  | "BILL_RECORDED"   // Printed on official utility invoice
  | "VERIFIED"        // Checked and reconciled against primary document
  | "REPORTED"        // Provided by stakeholder/study (pending meter audit)
  | "ASSUMED"         // Planning or engineering heuristic
  | "SIMULATED"       // Generated by physical model/dispatch scenario
  | "NEEDS_REVIEW";   // Uncertain, contradictory, or unreconciled evidence

export type VerificationState =
  | "VERIFIED"
  | "NEEDS_REVIEW"
  | "UNVERIFIED"
  | "DISCREPANCY_FLAGGED";

