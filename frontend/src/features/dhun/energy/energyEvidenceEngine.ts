/**
 * Calculates aggregate values across a collection of utility bills.
 * Does not overwrite source documents.
 */
export function calculateAggregateBills(bills: UtilityBillRecord[]): AggregateBillSummary {
  const combinedMonthlyKwh = bills.reduce((sum, b) => sum + b.consumptionKwh, 0);
  const combinedMonthlyMwh = combinedMonthlyKwh / 1000;
  const annualisedMwh = combinedMonthlyMwh * 12;

  const combinedConnectedCapacityKw = bills.reduce((sum, b) => sum + b.connectedLoadKw, 0);
  const sumRecordedBillingDemandKw = bills.reduce((sum, b) => sum + b.recordedBillingDemandKw, 0);

  const sumCurrentBillAmount = bills.reduce((sum, b) => sum + b.currentBillAmount, 0);
  const sumPreviousArrears = bills.reduce((sum, b) => sum + b.previousArrears, 0);

  // Effective rate is derived from current charges only (excluding arrears)
  const effectiveBillRatePerKwh =
    combinedMonthlyKwh > 0 ? sumCurrentBillAmount / combinedMonthlyKwh : 0;

  const discrepancyCount = bills.filter(
    (b) => !b.financialReconciliation.isReconciled || !b.meterReadings.readingMatchesPrinted
  ).length;

  return {
    combinedMonthlyKwh,
    combinedMonthlyMwh,
    annualisedMwh,
    combinedConnectedCapacityKw,
    sumRecordedBillingDemandKw,
    sumCurrentBillAmount,
    sumPreviousArrears,
    effectiveBillRatePerKwh,
    propertyCount: bills.length,
    hasActiveDiscrepancies: discrepancyCount > 0,
    discrepancyCount,
  };
}

/**
 * Reconciles Dhun's working campus energy assumption with historical reference evidence.
 *
 * Current Dhun baseline:
 * - ₹2.5 Lakh/month spend
 * - Assumed ₹10/kWh tariff
 * - Implies 25,000 kWh/month = 300 MWh/year
 */
export function reconcileBaselineWithEvidence(
  dhunMonthlySpend: number = 250000,
  dhunTariff: number = 10.0,
  bills: UtilityBillRecord[] = HISTORICAL_REFERENCE_BILLS
): BaselineReconciliation {
  const dhunDerivedMonthlyKwh = dhunTariff > 0 ? dhunMonthlySpend / dhunTariff : 0;
  const dhunDerivedAnnualMwh = (dhunDerivedMonthlyKwh * 12) / 1000;

  const agg = calculateAggregateBills(bills);
  const referenceMonthlyKwh = agg.combinedMonthlyKwh;
  const referenceAnnualMwh = agg.annualisedMwh;
  const referenceEffectiveRate = agg.effectiveBillRatePerKwh;

  const consumptionDifferenceMwh = dhunDerivedAnnualMwh - referenceAnnualMwh;
  const consumptionDeltaPercent =
    referenceAnnualMwh > 0
      ? ((dhunDerivedAnnualMwh - referenceAnnualMwh) / referenceAnnualMwh) * 100
      : 0;

  const tariffDifferencePerKwh = dhunTariff - referenceEffectiveRate;
  const tariffDeltaPercent =
    referenceEffectiveRate > 0
      ? ((dhunTariff - referenceEffectiveRate) / referenceEffectiveRate) * 100
      : 0;

  let verdict: BaselineReconciliation["verdict"] = "PARTIALLY_SUPPORTED";
  let verdictRationale = "";
  const recommendations: string[] = [];

  if (bills.length === 0) {
    verdict = "UNVERIFIED";
    verdictRationale = "No reference electricity bills registered for calibration.";
    recommendations.push("Ingest verified electricity bills to benchmark campus estimates.");
  } else {
    verdict = "INCOMPARABLE";
    verdictRationale =
      "Reference properties show an effective historical rate of ₹12.84/kWh across 190 kW connected capacity (133.59 MWh/yr). Dhun's working assumption of 300 MWh/yr is bill-derived (₹2.5L/mo @ ₹10/kWh) and represents an unmetered site. Denominators (floor area, guest days) are external and cannot be directly equated without verified physical meters.";

    recommendations.push(
      "Conduct a physical utility meter audit at Dhun 11kV Substation to establish an empirical baseline.",
      "Calibrate working tariff assumption: historical reference bills indicate ₹12.84/kWh all-in cost vs working assumption of ₹10.00/kWh (+28.4% variance).",
      "Do not normalize kWh/m² using external property benchmarks without documented architectural floor plans."
    );
  }

  return {
    dhunWorkingSpendMonthly: dhunMonthlySpend,
    dhunWorkingTariff: dhunTariff,
    dhunDerivedMonthlyKwh,
    dhunDerivedAnnualMwh,
    referenceMonthlyKwh,
    referenceAnnualMwh,
    referenceEffectiveRate,
    consumptionDifferenceMwh,
    consumptionDeltaPercent,
    tariffDifferencePerKwh,
    tariffDeltaPercent,
    verdict,
    verdictRationale,
    recommendations,
  };
}

/**
 * Calculates stacked campus energy totals combining:
 * 1. Existing campus estimate (default 300 MWh/yr)
 * 2. Planned buildings estimate (default 524 MWh/yr)
 * 3. Dynamic compute commons facility energy
 */
export function calculateStackedCampusDemand(
  existingCampusMwh: number,
  plannedBuildingsMwh: number,
  includePlannedBuildings: boolean,
  computeFacilityMwh: number,
  computeScenarioName: string,
  effectiveTariff: number = 10.0,
  gridEmissionFactorKgPerKwh: number = 0.71
): StackedCampusEnergyModel {
  const activePlannedMwh = includePlannedBuildings ? plannedBuildingsMwh : 0;
  const totalCampusDemandMwh = existingCampusMwh + activePlannedMwh + computeFacilityMwh;
  const totalCampusKwh = totalCampusDemandMwh * 1000;

  const totalElectricityCostLakh = (totalCampusKwh * effectiveTariff) / 100000;
  const gridEmissionsTco2e = (totalCampusKwh * gridEmissionFactorKgPerKwh) / 1000;

  return {
    existingCampusMwh,
    existingCampusSource: "Bill-derived: ₹2.5 Lakh/mo @ ₹10/kWh (pending 11kV meter audit)",
    plannedBuildingsMwh,
    plannedBuildingsSource: "Unvalidated engineering planning placeholder (524 MWh/yr)",
    includePlannedBuildings,
    computeFacilityMwh,
    computeScenarioName,
    totalCampusDemandMwh,
    totalElectricityCostLakh,
    blendedEffectiveTariff: effectiveTariff,
    gridEmissionsTco2e,
  };
}

/**
 * Utility to mask account numbers in user-facing dashboards.
 */
export function maskAccountNumber(acc: string): string {
  if (acc.length <= 4) return acc;
  const visible = acc.slice(-4);
  return `•••${visible}`;
}
